import { expect, test, type BrowserContext } from '@playwright/test'
import { createClient } from '@supabase/supabase-js'

test('personal publica treino e aluno registra série offline com confirmação posterior', async ({ page, browser }) => {
  test.setTimeout(150_000)
  const url = process.env.VITE_SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  test.skip(!url || !key, 'Requer Supabase local e chave de serviço só no processo de teste')
  const admin = createClient(url!, key!, { auth: { persistSession: false, autoRefreshToken: false } })
  const suffix = crypto.randomUUID()
  const professionalEmail = `coach-workout-${suffix}@example.invalid`
  const studentEmail = `student-workout-${suffix}@example.invalid`
  const professionalPassword = `Test-${crypto.randomUUID()}!`
  const studentPassword = `Test-${crypto.randomUUID()}!`
  let tenantId = '', professionalId = '', studentUserId = ''
  let studentId: string
  let studentContext: BrowserContext | null = null
  try {
    const professional = await admin.auth.admin.createUser({ email: professionalEmail, password: professionalPassword, email_confirm: true })
    expect(professional.error).toBeNull(); professionalId = professional.data.user!.id
    const student = await admin.auth.admin.createUser({ email: studentEmail, password: studentPassword, email_confirm: true })
    expect(student.error).toBeNull(); studentUserId = student.data.user!.id
    const tenant = await admin.from('tenants').insert({ name: `Espaço Treino ${suffix}` }).select('id').single()
    expect(tenant.error).toBeNull(); tenantId = tenant.data!.id
    expect((await admin.from('tenant_brand').insert({ tenant_id: tenantId, brand_name: 'Treino de teste', display_name: 'Personal de teste', accent_color: '#123B36', secondary_color: '#FFFFFF' })).error).toBeNull()
    expect((await admin.from('tenant_memberships').insert([
      { tenant_id: tenantId, user_id: professionalId, role: 'PROFISSIONAL' },
      { tenant_id: tenantId, user_id: studentUserId, role: 'ALUNO' },
    ])).error).toBeNull()
    expect((await admin.from('professionals').insert({ tenant_id: tenantId, user_id: professionalId, display_name: 'Personal de teste' })).error).toBeNull()
    const studentRow = await admin.from('students').insert({ tenant_id: tenantId, user_id: studentUserId, full_name: 'Aluno Treino', email: studentEmail }).select('id').single()
    expect(studentRow.error).toBeNull(); studentId = studentRow.data!.id

    await page.goto('/login')
    await page.getByLabel('E-mail').fill(professionalEmail)
    await page.getByLabel('Senha').fill(professionalPassword)
    await page.getByRole('button', { name: 'Entrar' }).click()
    await expect(page.getByRole('heading', { name: 'Área do personal' })).toBeVisible()
    await page.getByRole('link', { name: 'Exercícios', exact: true }).click()
    await page.getByRole('button', { name: 'Novo exercício' }).click()
    await page.getByLabel('Nome do exercício').fill('Exercício de teste')
    await page.locator('.exercise-create-form').getByLabel('Grupo principal').selectOption('PEITO')
    await page.getByLabel('Suas instruções').fill('Instrução fictícia para teste.')
    await page.locator('.exercise-create-form').getByLabel('Enviar MP4').check()
    await page.locator('.exercise-create-form').getByLabel('Arquivo MP4').setInputFiles({ name: 'instrucao.mp4', mimeType: 'video/mp4', buffer: Buffer.from('000000186674797069736f6d0000020069736f6d', 'hex') })
    await page.getByRole('button', { name: 'Adicionar exercício' }).click()
    await expect(page.getByRole('heading', { name: 'Peito' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Exercício de teste' })).toBeVisible()
    await expect(page.getByText('Com vídeo', { exact: false })).toBeVisible()
    await page.getByRole('button', { name: 'Novo exercício' }).click()
    await page.getByLabel('Nome do exercício').fill('Mobilidade fictícia')
    await page.locator('.exercise-create-form').getByLabel('Grupo principal').selectOption('MOBILIDADE')
    await page.getByRole('button', { name: 'Adicionar exercício' }).click()
    await expect(page.getByText('Sem vídeo · pode adicionar depois')).toBeVisible()
    const mobility = page.locator('.exercise-library-card').filter({ has: page.getByRole('heading', { name: 'Mobilidade fictícia' }) })
    await mobility.getByRole('button', { name: 'Editar exercício' }).click()
    await mobility.getByLabel('Link do YouTube', { exact: true }).check()
    await expect(mobility.getByLabel('Arquivo MP4')).toHaveCount(0)
    await mobility.getByRole('textbox', { name: 'Link do YouTube' }).fill('https://youtu.be/dQw4w9WgXcQ')
    await mobility.getByRole('button', { name: 'Salvar exercício' }).click()
    await expect(mobility.getByText('Com vídeo')).toBeVisible()
    await expect(mobility.getByRole('dialog', { name: 'Vídeo de instrução' })).toHaveCount(0)
    const savedMobility = await admin.from('exercise_library').select('id,video_url').eq('tenant_id', tenantId).eq('name', 'Mobilidade fictícia').single()
    expect(savedMobility.error).toBeNull()
    expect(savedMobility.data?.video_url).toBe('https://www.youtube.com/watch?v=dQw4w9WgXcQ')
    await mobility.getByRole('button', { name: 'Editar exercício' }).click()
    await mobility.getByRole('button', { name: 'Ver vídeo online' }).click()
    await expect(mobility.getByRole('dialog', { name: 'Vídeo de instrução' }).locator('iframe')).toHaveAttribute('src', 'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ?autoplay=1')
    await mobility.getByRole('button', { name: 'Fechar vídeo' }).click()
    await expect(mobility.getByRole('dialog', { name: 'Vídeo de instrução' })).toHaveCount(0)
    await mobility.getByRole('button', { name: 'Fechar' }).click()
    await page.locator('.exercise-filters select').selectOption('MOBILIDADE')
    await expect(page.getByRole('heading', { name: 'Mobilidade fictícia' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Exercício de teste' })).toHaveCount(0)
    await page.locator('.exercise-filters select').selectOption('TODOS')
    await page.getByLabel('Buscar exercício').fill('exercicio de teste')
    await expect(page.getByRole('heading', { name: 'Exercício de teste' })).toBeVisible()
    await page.getByLabel('Buscar exercício').fill('')
    await page.goto(`/app/alunos/${studentId}`, { waitUntil: 'domcontentloaded', timeout: 15_000 })
    await page.getByRole('tab', { name: 'Treino' }).click()
    await expect(page.getByText('Nenhum treino publicado para este aluno.')).toBeVisible()
    await page.getByRole('tab', { name: 'Atendimento' }).click()
    await page.getByLabel('Nome do atendimento').fill('Treino personalizado')
    await page.getByRole('button', { name: 'Salvar atendimento' }).click()
    await expect(page.getByText('Atendimento atualizado.')).toBeVisible()
    await page.getByRole('tab', { name: 'Treino' }).click()
    await page.getByRole('button', { name: 'Adicionar exercício' }).click()
    await page.locator('.workout-guidance-editor summary').click()
    await page.getByLabel('Orientações para este aluno').fill('Orientação fictícia do plano.')
    await page.getByLabel('Início do ciclo').fill(new Date().toISOString().slice(0, 10))
    await page.getByLabel('Duração (semanas)').fill('8')
    await page.getByLabel('Orientação essencial antes de começar').fill('Leia as orientações antes do treino.')
    await page.getByLabel('Descanso (segundos)').fill('75')
    await page.getByLabel('Tipo e alvo de cada série').fill('Aquecimento · 10\nVálida 1 · 8 a 12\nVálida 2 · 8 a 12')
    await page.getByLabel('Orientação específica para este aluno').fill('Observação fictícia individual.')
    await page.getByRole('button', { name: 'Adicionar exercício' }).click()
    await page.getByLabel('Tipo de registro').selectOption('PREPARATION')
    await page.getByLabel('Etapas').fill('2')
    await page.getByLabel('Repetições alvo').fill('20 segundos')
    await page.getByLabel('Como o aluno registra').selectOption('TIME')
    await page.getByRole('button', { name: 'Adicionar dia' }).click()
    await expect(page.getByLabel('Nome do dia 2')).toBeVisible()
    await expect(page.locator('.workout-exercise-card')).toHaveCount(0)
    await page.getByRole('button', { name: 'Adicionar exercício' }).click()
    await page.locator('.workout-item-row select').first().selectOption({ label: 'Mobilidade fictícia' }, { timeout: 10_000 })
    await page.getByLabel('Séries', { exact: true }).fill('2')
    await page.getByLabel('Repetições alvo').fill('20 segundos')
    await page.getByLabel('Como o aluno registra').selectOption('TIME')
    await page.locator('.workout-day-tabs button').first().click()
    await expect(page.locator('.workout-exercise-card')).toHaveCount(2)
    await page.getByRole('button', { name: 'Mover depois' }).click()
    await expect(page.locator('.workout-day-tabs button').nth(1)).toContainText('Treino A')
    await page.getByRole('button', { name: 'Mover antes' }).click()
    await expect(page.locator('.workout-day-tabs button').first()).toContainText('Treino A')
    await page.getByRole('button', { name: 'Editar' }).first().click()
    await expect(page.getByLabel('Orientação específica para este aluno')).toHaveValue('Observação fictícia individual.')
    await page.getByRole('button', { name: 'Salvar rascunho' }).click()
    await expect(page.getByText('Rascunho salvo.')).toBeVisible()
    const savedPlan = await admin.from('workout_plans').select('id,draft').eq('student_id', studentId).single()
    expect(savedPlan.error).toBeNull()
    expect((await admin.from('workout_plans').update({ draft: { ...savedPlan.data!.draft, reviewRequired: true } }).eq('id', savedPlan.data!.id)).error).toBeNull()
    await page.reload()
    await expect(page.getByRole('tab', { name: 'Treino' })).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('button', { name: 'Publicar para aluno' })).toBeDisabled()
    await page.getByRole('button', { name: 'Revisei o treino e quero liberar a publicação' }).click()
    await page.getByRole('button', { name: 'Publicar para aluno' }).click()
    await page.getByRole('button', { name: 'Confirmar publicação' }).click()
    await expect(page.getByText('Treino publicado e entregue ao aluno.')).toBeVisible()
    await page.getByRole('link', { name: 'Exercícios', exact: true }).click()
    const publishedMobility = page.locator('.exercise-library-card').filter({ has: page.getByRole('heading', { name: 'Mobilidade fictícia' }) })
    await publishedMobility.getByRole('button', { name: 'Editar exercício' }).click()
    await publishedMobility.getByLabel('Link do YouTube', { exact: true }).check()
    await publishedMobility.getByRole('textbox', { name: 'Link do YouTube' }).fill('https://youtu.be/9bZkp7q19f0')
    await publishedMobility.getByRole('button', { name: 'Salvar exercício' }).click()
    await expect(publishedMobility.getByText('Alunos com este exercício verão a mídia atual')).toBeVisible()
    await page.goto(`/app/alunos/${studentId}?aba=treino`)
    await expect(page.getByText('Vídeos da biblioteca aparecem para o aluno')).toBeVisible()
    const unchangedSnapshot = await admin.from('workout_plan_versions').select('snapshot').eq('plan_id', savedPlan.data!.id).order('version_number', { ascending: false }).limit(1).maybeSingle()
    expect(unchangedSnapshot.error).toBeNull()
    expect(unchangedSnapshot.data?.snapshot.days[1].items[0].videoUrl).toBe('https://www.youtube.com/watch?v=dQw4w9WgXcQ')
    await page.getByRole('button', { name: 'Sair' }).click()

    studentContext = await browser.newContext({ baseURL: 'http://127.0.0.1:4173' })
    const studentPage = await studentContext.newPage()
    await studentPage.goto('/login')
    await studentPage.getByLabel('E-mail').fill(studentEmail)
    await studentPage.getByLabel('Senha').fill(studentPassword)
    await studentPage.getByRole('button', { name: 'Entrar' }).click()
    await expect(studentPage).toHaveURL(/\/aluno\/inicio$/)
    await expect(studentPage.getByRole('heading', { name: 'Seu treino' })).toBeVisible()
    await expect(studentPage.getByRole('heading', { name: 'Área do aluno' })).toHaveCount(0)
    await expect(studentPage.locator('.student-app-brand')).toContainText('Treino de teste')
    expect(await studentPage.locator('.student-experience').evaluate(element => getComputedStyle(element).getPropertyValue('--student-accent').trim().toLowerCase())).toBe('#123b36')
    await expect(studentPage.getByText('Seu atendimento: Treino personalizado')).toBeVisible()
    await expect(studentPage.getByText('Leia as orientações antes do treino.')).toBeVisible()
    expect(await studentPage.locator('.student-week-nav').evaluate(element => getComputedStyle(element).display)).toBe('grid')
    await studentPage.setViewportSize({ width: 390, height: 844 })
    expect(await studentPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(studentPage.getByText('Orientação fictícia do plano.')).toBeHidden()
    await studentPage.locator('.student-workout-guidance summary').click()
    await expect(studentPage.getByText('Orientação fictícia do plano.')).toBeVisible()
    await expect(studentPage.locator('.student-day-tabs button')).toHaveCount(2)
    await expect(studentPage.locator('.student-exercise-card')).toHaveCount(2)
    await studentPage.locator('.student-day-tabs button').nth(1).click()
    await expect(studentPage.getByRole('heading', { name: 'Treino B' })).toBeVisible()
    await expect(studentPage.locator('.student-exercise-card')).toHaveCount(1)
    if (await studentPage.locator('.student-exercise-toggle').getAttribute('aria-expanded') === 'false') await studentPage.locator('.student-exercise-toggle').click()
    const youtubeTrigger = studentPage.getByRole('button', { name: 'Ver vídeo online' })
    await youtubeTrigger.click()
    await expect(studentPage.getByRole('dialog', { name: 'Vídeo de instrução' }).locator('iframe')).toHaveAttribute('src', 'https://www.youtube-nocookie.com/embed/9bZkp7q19f0?autoplay=1')
    await studentPage.keyboard.press('Escape')
    await expect(studentPage.getByRole('dialog', { name: 'Vídeo de instrução' })).toHaveCount(0)
    await expect(youtubeTrigger).toBeFocused()
    await studentPage.locator('.student-day-tabs button').first().click()
    await studentPage.getByRole('button', { name: 'Começar treino do dia 1' }).click()
    await expect(studentPage.locator('.student-exercise-card')).toHaveCount(2)
    await expect(studentPage.getByText('Observação fictícia individual.')).toBeVisible()
    await expect(studentPage.getByText('Descanso previsto: 75 s')).toBeVisible()
    await expect(studentPage.getByText('Aquecimento · 10')).toBeVisible()
    await studentPage.getByRole('button', { name: 'Ver vídeo online' }).first().click()
    await expect(studentPage.getByRole('dialog', { name: 'Vídeo de instrução' }).locator('video')).toBeVisible()
    await studentPage.getByRole('button', { name: 'Fechar vídeo' }).click()
    await studentPage.evaluate(async () => { await navigator.serviceWorker.ready })
    await studentContext.setOffline(true)
    expect(await studentPage.evaluate(() => navigator.onLine)).toBe(false)
    const firstSet = studentPage.locator('.workout-set').first()
    await firstSet.getByLabel('Repetições feitas').fill('10')
    await firstSet.getByLabel('Carga').fill('20')
    await firstSet.getByLabel('Repetições que sobrariam').fill('2')
    await firstSet.getByRole('button', { name: 'Registrar série' }).click()
    await expect(studentPage.getByText(/aguardando confirmação/)).toBeVisible()
    await studentPage.reload()
    await expect(studentPage.locator('.student-exercise-card')).toHaveCount(2)
    expect(await studentPage.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await expect(studentPage.locator('.workout-set')).toHaveCount(1)
    await expect(studentPage.locator('.student-week-nav')).toContainText('0 completos')
    await expect(studentPage.getByText(/aguardando confirmação/)).toBeVisible()
    await studentContext.setOffline(false)
    await expect(studentPage.getByText('Lançamentos confirmados no servidor.')).toBeVisible({ timeout: 30_000 })
    await studentPage.locator('.student-exercise-card').first().locator('.student-saved-sets button').first().click()
    await expect(studentPage.locator('.workout-set').getByLabel('Repetições feitas')).toHaveValue('10')
    await studentPage.locator('.workout-set').getByRole('button', { name: 'Salvar correção' }).click()
    await expect(studentPage.locator('.student-exercise-card').first().locator('.student-entry-progress')).toContainText('1 de 3 séries registradas')
    await expect(studentPage.getByRole('button', { name: 'Concluir treino do dia' })).toHaveCount(0)
    await expect(studentPage.getByRole('button', { name: 'Encerrar como parcial' })).toBeVisible()
    for (const index of [1, 2]) {
      const set = studentPage.locator('.workout-set').first()
      await expect(set).toContainText(`${index + 1} de 3`)
      await set.getByLabel('Repetições feitas').fill('10')
      await set.getByRole('button', { name: index === 2 ? 'Salvar e continuar' : 'Registrar série' }).click()
    }
    const preparation = studentPage.locator('.student-exercise-card').nth(1)
    await expect(preparation.locator('.student-exercise-toggle')).toHaveAttribute('aria-expanded', 'true')
    await expect(studentPage.locator('.student-exercise-card').first().locator('.student-exercise-toggle')).toHaveAttribute('aria-expanded', 'false')
    await expect(preparation).toContainText('2 etapas')
    await expect(preparation.getByLabel('Carga')).toHaveCount(0)
    await expect(preparation.getByLabel('Repetições que sobrariam')).toHaveCount(0)
    for (const index of [0, 1]) {
      const step = preparation.locator('.workout-set').first()
      await expect(step).toContainText(`${index + 1} de 2`)
      await step.getByLabel('Tempo feito').fill('20')
      await step.getByRole('button', { name: index === 1 ? 'Salvar e continuar' : 'Registrar etapa' }).click()
    }
    await studentPage.getByRole('button', { name: 'Concluir treino do dia' }).click()
    await expect(studentPage.locator('.student-week-nav')).toContainText('1 completos')
    await studentPage.locator('.student-day-tabs button').nth(1).click()
    await studentPage.getByRole('button', { name: 'Começar treino do dia 2' }).click()
    const timedSet = studentPage.locator('.workout-set').first()
    await timedSet.getByLabel('Tempo feito').fill('20')
    await timedSet.getByRole('button', { name: 'Registrar série' }).click()
    await studentPage.getByRole('button', { name: 'Encerrar como parcial' }).click()
    await studentPage.getByRole('button', { name: 'Confirmar encerramento parcial' }).click()
    await expect(studentPage.locator('.student-week-nav')).toContainText('1 parciais')
    const stored = await admin.from('workout_sessions').select('entries,revision,day_id,week_start').eq('student_id', studentId).eq('status', 'COMPLETED').single()
    expect(stored.error).toBeNull()
    expect(stored.data?.day_id).toBe(savedPlan.data!.draft.days[0].id)
    expect(stored.data?.week_start).toMatch(/^\d{4}-\d{2}-\d{2}$/)
    expect(stored.data?.entries).toEqual(expect.arrayContaining([expect.objectContaining({ reps: 10, loadKg: 20, rir: 2 })]))
    const partial = await admin.from('workout_sessions').select('entries,status').eq('student_id', studentId).eq('status', 'PARTIAL').single()
    expect(partial.error).toBeNull()
    expect(partial.data?.entries).toEqual([expect.objectContaining({ durationSeconds: 20 })])
  } finally {
    if (studentContext) { await studentContext.setOffline(false); await studentContext.close() }
    if (tenantId) {
      const { data: exerciseFolders } = await admin.storage.from('exercise-videos').list(tenantId)
      for (const folder of exerciseFolders ?? []) {
        const { data: files } = await admin.storage.from('exercise-videos').list(`${tenantId}/${folder.name}`)
        if (files?.length) await admin.storage.from('exercise-videos').remove(files.map(file => `${tenantId}/${folder.name}/${file.name}`))
      }
      const { data: sessions } = await admin.from('workout_sessions').select('id').eq('tenant_id', tenantId)
      for (const session of sessions ?? []) await admin.from('workout_operation_receipts').delete().eq('session_id', session.id)
      await admin.from('workout_sessions').delete().eq('tenant_id', tenantId)
      await admin.from('workout_assignments').delete().eq('tenant_id', tenantId)
      await admin.from('workout_plan_versions').delete().eq('tenant_id', tenantId)
      await admin.from('workout_plans').delete().eq('tenant_id', tenantId)
      await admin.from('exercise_library').delete().eq('tenant_id', tenantId)
      await admin.from('student_service_plans').delete().eq('tenant_id', tenantId)
      await admin.from('student_invitations').delete().eq('tenant_id', tenantId)
      await admin.from('student_internal_notes').delete().eq('tenant_id', tenantId)
      await admin.from('students').delete().eq('tenant_id', tenantId)
      await admin.from('audit_events').delete().eq('tenant_id', tenantId)
      await admin.from('professionals').delete().eq('tenant_id', tenantId)
      await admin.from('tenant_memberships').delete().eq('tenant_id', tenantId)
      await admin.from('tenant_brand').delete().eq('tenant_id', tenantId)
      await admin.from('tenant_plans').delete().eq('tenant_id', tenantId)
      await admin.from('tenants').delete().eq('id', tenantId)
    }
    if (studentUserId) await admin.auth.admin.deleteUser(studentUserId)
    if (professionalId) await admin.auth.admin.deleteUser(professionalId)
  }
})
